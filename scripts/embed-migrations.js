/**
 * Reads drizzle/*.sql migration files (sorted) and embeds them into
 * src/db/migrations.generated.ts so the app bundles them without needing
 * .sql imports or babel plugins. Run after every `drizzle-kit generate`:
 *
 *   node scripts/embed-migrations.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'drizzle');
const outFile = path.join(__dirname, '..', 'src', 'db', 'migrations.generated.ts');

const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const migrations = files.map((f) => {
  const sql = fs.readFileSync(path.join(dir, f), 'utf8');
  // drizzle separates statements with the statement-breakpoint marker
  const statements = sql
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean);
  return { name: f.replace(/\.sql$/, ''), statements };
});

const body = `// AUTO-GENERATED by scripts/embed-migrations.js — do not edit by hand.
export type Migration = { name: string; statements: string[] };

export const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

fs.writeFileSync(outFile, body);
console.log(`Embedded ${migrations.length} migration(s) into src/db/migrations.generated.ts`);
